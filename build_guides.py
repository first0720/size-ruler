def build(p):
    sections = []
    for t in p["tables"]:
        head = "".join(f'<th scope="col">{h}</th>' for h in t["head"])
        rows = ""
        for r in t["rows"]:
            cells = ""
            for i, v in enumerate(r):
                if i == t["highlight"]:
                    cells += f'<th scope="row">{v}</th>'
                else:
                    cells += f"<td>{v}</td>"
            rows += f"<tr>{cells}</tr>\n          "
        # 칸에 문장이 들어가는 표는 줄바꿈을 허용한다 (표시만 바뀜)
        tcls = "pick-table is-text" if any(len(str(v)) > 14 for r in t["rows"] for v in r) else "pick-table"
        sections.append(f"""
  <section>
    <h2>{t['h2']}</h2>
    <p>{t['intro']}</p>
    <div class="scroller">
      <table class="{tcls}">
        <caption>{t['caption']}</caption>
        <thead>
          <tr>{head}</tr>
        </thead>
        <tbody>
          {rows.rstrip()}
        </tbody>
      </table>
    </div>
  </section>
""")
    # 첫 표는 넓은 화면에서 결론 옆에 선다
    first_table, rest_tables = sections[0], "".join(sections[1:])
